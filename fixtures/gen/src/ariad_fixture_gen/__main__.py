"""Command-line entry point for regenerating the fixture suite."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import tomllib

from ariad_fixture_gen import docx, editor_roundtrip, epub, heavy, heavy_office, html, image, markdown, office, pdf, scan, truth
from ariad_fixture_gen.manifest import update_generated_hashes


def _check(root: Path, outputs: dict[str, bytes]) -> list[str]:
    records = tomllib.loads((root / "fixtures/manifest.toml").read_text())["fixture"]
    hashes = {}
    for record in records:
        if record["origin"] == "generated":
            hashes[record["path"]] = record["sha256"]
            hashes.update({item["path"]: item["sha256"] for item in record.get("companions", [])})
    errors = []
    for path, content in sorted(outputs.items()):
        if not path.startswith("fixtures/") or ".." in Path(path).parts:
            errors.append(f"Unsafe generated path: {path}")
            continue
        if path not in hashes:
            errors.append(f"Undeclared generated path: {path}")
        elif hashes[path] != hashlib.sha256(content).hexdigest():
            errors.append(f"Recorded hash differs: {path}")
        actual = root / path
        if not actual.is_file() or actual.read_bytes() != content:
            errors.append(f"Generated bytes differ: {path}")
    editor_paths = {path for path in hashes if path.startswith(editor_roundtrip.PREFIX)}
    if any(path.startswith(editor_roundtrip.PREFIX) for path in outputs):
        errors.extend(f"Declared editor path was not generated: {path}" for path in sorted(editor_paths - outputs.keys()))
    return errors


def main(root: Path | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    generators = {
        "md": markdown.generate,
        "html": html.generate,
        "docx": docx.generate,
        "epub": epub.generate,
        "pdf": pdf.generate,
        "scan": scan.generate,
        "image": image.generate,
        "office": office.generate,
        "truth": truth.generate,
        "heavy": heavy.generate,
        "heavy-office": heavy_office.generate,
        "editor-roundtrip": editor_roundtrip.generate,
    }
    parser.add_argument("--only", choices=(*generators, "all"), default="all")
    parser.add_argument("--check", action="store_true", help="Compare generated bytes and manifest hashes without writing")
    args = parser.parse_args()

    root = root or Path(__file__).resolve().parents[4]
    selected = generators if args.only == "all" else {args.only: generators[args.only]}
    outputs = {path: content for generator in selected.values() for path, content in generator(root).items()}
    if args.check:
        errors = _check(root, outputs)
        if errors:
            parser.exit(1, "\n".join(errors) + "\n")
        print(f"Checked {len(outputs)} generated files and their manifest hashes; no changes.")
        return
    for relative_path, content in sorted(outputs.items()):
        output_path = root / relative_path
        output_path.parent.mkdir(parents=True, exist_ok=True)
        if not output_path.exists() or output_path.read_bytes() != content:
            output_path.write_bytes(content)

    update_generated_hashes(root, set(outputs))
    families = ", ".join(selected)
    print(f"Generated {len(outputs)} files for {families} fixtures and updated their manifest hashes.")


if __name__ == "__main__":
    main()
