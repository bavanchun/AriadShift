"""The Windows review binds metadata, notices and dynamically imported source."""

import hashlib
import sys
from importlib import metadata

import pytest
from conftest import REPOSITORY

sys.path.insert(0, str(REPOSITORY / "engines/docling/pack"))
import licenses

EXPRESSION = "BSD-3-Clause AND HPND AND LGPL-2.1-or-later AND MIT AND PSF-2.0 AND Python-2.0"


@pytest.fixture
def reviewed(tmp_path, monkeypatch):
    info = tmp_path / "pywin32-312.dist-info"
    notice = info / "licenses/adodbapi/license.txt"
    notice.parent.mkdir(parents=True)
    notice.write_text("GNU LESSER GENERAL PUBLIC LICENSE\nVersion 2.1\n", encoding="utf-8")
    (info / "METADATA").write_text(
        "Name: pywin32\nVersion: 312\nLicense: PSF\n"
        "Classifier: License :: OSI Approved :: Python Software Foundation License\n"
        "License-File: adodbapi/license.txt\n",
        encoding="utf-8",
    )
    (info / "RECORD").write_text(f"{info.name}/licenses/adodbapi/license.txt,,\n", encoding="utf-8")
    source = tmp_path / "adodbapi"
    source.mkdir()
    (source / "__init__.py").write_text("# Unmodified library\n", encoding="utf-8")
    (source / "README.txt").write_text("Source included\n", encoding="utf-8")
    lines = sorted(
        f"{p.relative_to(source).as_posix()} {hashlib.sha256(p.read_bytes()).hexdigest()}"
        for p in source.rglob("*")
        if p.is_file()
    )
    monkeypatch.setattr(
        licenses,
        "_PYWIN32_REVIEW",
        {
            "version": "312",
            "library_version": "2.6.2.0",
            "source": "https://example.org/pywin32/b312.tar.gz",
            "metadata_sha256": hashlib.sha256(
                (info / "METADATA").read_text(encoding="utf-8").encode()
            ).hexdigest(),
            "payload_sha256": hashlib.sha256("\n".join(lines).encode()).hexdigest(),
            "notices": {"adodbapi/license.txt": hashlib.sha256(notice.read_bytes()).hexdigest()},
        },
        raising=False,
    )
    return metadata.PathDistribution(info), info, source, notice


def test_exact_review_accepts_composite_without_generic_lgpl_permission(reviewed):
    dist, _, _, _ = reviewed
    assert licenses.check([dist]) == []
    assert licenses.license_of(dist) == EXPRESSION
    assert licenses.verdict("pywin32", "LGPL-2.1-or-later") is not None
    assert "LGPL-2.1-or-later" not in licenses.ALLOWED


@pytest.mark.parametrize(
    "change",
    [
        "metadata",
        "version",
        "notice",
        "missing-notice",
        "record",
        "source",
        "extra-source",
        "static",
    ],
)
def test_review_refuses_changed_payload_or_declaration(reviewed, change):
    dist, info, source, notice = reviewed
    if change == "metadata":
        with (info / "METADATA").open("a", encoding="utf-8") as stream:
            stream.write("License-Expression: GPL-3.0-only\n")
    elif change == "version":
        (info / "METADATA").write_text(
            "Name: pywin32\nVersion: 313\nLicense-Expression: MIT\n", encoding="utf-8"
        )
    elif change == "notice":
        notice.write_text("Changed notice\n", encoding="utf-8")
    elif change == "missing-notice":
        notice.unlink()
    elif change == "record":
        (info / "RECORD").write_text("", encoding="utf-8")
    elif change == "source":
        (source / "__init__.py").write_text("# Modified\n", encoding="utf-8")
    else:
        (source / ("extra.py" if change == "extra-source" else "static.a")).write_bytes(b"extra")
    assert licenses.check([dist])
    assert licenses.license_of(dist) is None


def test_generated_bytecode_does_not_modify_reviewed_source(reviewed):
    dist, _, source, _ = reviewed
    cache = source / "__pycache__"
    cache.mkdir()
    (cache / "__init__.cpython-314.pyc").write_bytes(b"generated bytecode")
    assert licenses.check([dist]) == []


def test_writer_bundles_reviewed_notice_and_source_pointer(reviewed, tmp_path):
    dist, _, source, notice = reviewed
    destination = tmp_path / "notices"
    licenses.write_notices([dist], destination)
    packet = destination / "python/pywin32-312"
    assert (packet / "licenses/adodbapi/license.txt").read_bytes() == notice.read_bytes()
    pointer = (packet / "adodbapi-source.txt").read_text(encoding="utf-8")
    assert "2.6.2.0" in pointer and "LGPL-2.1-or-later" in pointer
    assert "https://example.org/pywin32/b312.tar.gz" in pointer
    (source / "__init__.py").write_text("# Modified\n", encoding="utf-8")
    with pytest.raises(SystemExit, match="pywin32"):
        licenses.write_notices([dist], tmp_path / "changed-notices")
